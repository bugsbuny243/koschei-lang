"""Generated reference documentation (readiness gate G7).

Two references are rendered from the sources that define them, so they can
never drift from the toolchain:

* ``docs/reference/ERROR_CODES.md`` from the diagnostic catalogs (every code,
  Turkish and English);
* ``docs/reference/CORE_LIBRARY.md`` from the Koschei sources under
  ``koschei/core_library/`` (module notes, structs and function signatures
  with the comment written above each one).

``python -m koschei.reference_docs_v1 --write`` regenerates both files;
``--check`` fails when a committed file is stale.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

from .core_library_v1 import CORE_LIBRARY_MODULES_V1
from .diagnostics import CATALOG, ENGLISH_CATALOG

ROOT = Path(__file__).resolve().parent.parent
LIBRARY = Path(__file__).resolve().parent / "core_library"
ERROR_CODES_PATH = ROOT / "docs" / "reference" / "ERROR_CODES.md"
CORE_LIBRARY_PATH = ROOT / "docs" / "reference" / "CORE_LIBRARY.md"

_HEADER = "<!-- Generated by `python -m koschei.reference_docs_v1 --write`. Do not edit. -->\n"
_FUNCTION = re.compile(r"^(pure\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)(.*)\{\s*$")
_STRUCT = re.compile(r"^struct\s+([A-Za-z_][A-Za-z0-9_<>, ]*)\s*\{\s*$")


def _family(code: str) -> str:
    digits = code[2:]
    return {
        "1": "Söz dizimi ve tipler / Syntax and types",
        "2": "Yetki ve güvenlik / Authority and security",
        "3": "Çalışma zamanı / Runtime",
        "4": "Native derleme / Native build",
        "5": "Derleyici bütünlüğü / Compiler integrity",
    }.get(digits[0], "Diğer / Other")


def render_error_codes() -> str:
    lines = [
        _HEADER,
        "# Koschei Error Codes / Hata Kodları\n",
        f"{len(CATALOG)} codes. `ks explain KSxxxx` prints the same text; "
        "`ks --lang en explain KSxxxx` the English one.\n",
    ]
    current = None
    for code in sorted(CATALOG):
        family = _family(code)
        if family != current:
            lines.append(f"\n## {family}\n")
            current = family
        tr = CATALOG[code]
        en = ENGLISH_CATALOG[code]
        lines.append(f"\n### {code} — {en.title}\n")
        lines.append(f"\n**EN.** {en.summary} {en.why}\n")
        lines.append(f"\n*Fix:* {en.fix}\n")
        lines.append(f"\n**TR — {tr.title}.** {tr.summary} {tr.why}\n")
        lines.append(f"\n*Düzeltme:* {tr.fix}\n")
        if tr.example.strip():
            # Some examples are raw HTTP with CRLF line ends; Markdown keeps LF.
            example = tr.example.replace("\r\n", "\n").strip()
            lines.append("\n```ks\n" + example + "\n```\n")
    return "".join(lines)


def _comment_block(lines: list[str], index: int) -> list[str]:
    block: list[str] = []
    cursor = index - 1
    while cursor >= 0 and lines[cursor].startswith("//"):
        block.append(lines[cursor][2:].strip())
        cursor -= 1
    return list(reversed(block))


def _module_notes(lines: list[str]) -> list[str]:
    notes: list[str] = []
    for line in lines:
        if not line.startswith("//"):
            break
        notes.append(line[2:].strip())
    # The first line is the "Koschei Core Library: <name>" banner.
    return notes[1:] if notes else []


def _paragraph(texts: list[str]) -> str:
    paragraphs: list[list[str]] = [[]]
    for text in texts:
        if text:
            paragraphs[-1].append(text)
        elif paragraphs[-1]:
            paragraphs.append([])
    return "\n\n".join(" ".join(item) for item in paragraphs if item)


def render_core_library() -> str:
    out = [
        _HEADER,
        "# Koschei Core Library Reference\n",
        "\nEvery module is written in Koschei and compiled with the program that "
        "imports it (`import text`). See `docs/CORE_LIBRARY_V1.md` for the design "
        "rules.\n",
        "\n| Module | Functions | Structs |\n|---|---|---|\n",
    ]
    sections: list[str] = []
    for name in CORE_LIBRARY_MODULES_V1:
        source = (LIBRARY / f"{name}.ks").read_text(encoding="utf-8")
        lines = source.splitlines()
        functions: list[tuple[str, str, str]] = []
        structs: list[tuple[str, list[str], str]] = []
        for index, line in enumerate(lines):
            match = _FUNCTION.match(line)
            if match:
                pure = "pure " if match.group(1) else ""
                signature = f"{pure}fn {match.group(2)}{match.group(3).rstrip()}"
                functions.append(
                    (match.group(2), signature, _paragraph(_comment_block(lines, index)))
                )
                continue
            match = _STRUCT.match(line)
            if match:
                fields: list[str] = []
                cursor = index + 1
                while cursor < len(lines) and lines[cursor].strip() != "}":
                    text = lines[cursor].strip()
                    if text and not text.startswith("//"):
                        fields.append(text.rstrip(","))
                    cursor += 1
                structs.append(
                    (match.group(1).strip(), fields, _paragraph(_comment_block(lines, index)))
                )
        out.append(f"| [`{name}`](#{name}) | {len(functions)} | {len(structs)} |\n")
        section = [f"\n## {name}\n"]
        notes = _paragraph(_module_notes(lines))
        if notes:
            section.append(f"\n{notes}\n")
        for struct_name, fields, comment in structs:
            section.append(f"\n### struct `{struct_name}`\n")
            if comment:
                section.append(f"\n{comment}\n")
            section.append("\n```ks\n" + "\n".join(fields) + "\n```\n")
        for function_name, signature, comment in functions:
            section.append(f"\n### `{name}.{function_name}`\n")
            section.append(f"\n```ks\n{signature}\n```\n")
            if comment:
                section.append(f"\n{comment}\n")
        sections.append("".join(section))
    return "".join(out) + "".join(sections)


GENERATED = {
    ERROR_CODES_PATH: render_error_codes,
    CORE_LIBRARY_PATH: render_core_library,
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="koschei-reference-docs")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the reference files")
    mode.add_argument("--check", action="store_true", help="fail when a reference is stale")
    args = parser.parse_args(argv)
    stale: list[str] = []
    for path, render in GENERATED.items():
        text = render()
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("stale generated reference: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
